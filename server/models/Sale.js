const mongoose = require('mongoose');

const saleSchema = new mongoose.Schema({
  items: [
    {
      variant: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Variant',
        required: true
      },
      // Denormalized at sale time so a receipt/report still reads correctly
      // even if the style/variant is later edited or deactivated.
      styleName: { type: String, required: true },
      size: { type: String, required: true },
      color: { type: String, required: true },
      unitPrice: { type: Number, required: true }, // price actually charged (basePrice or priceOverride) at sale time
      quantity: {
        type: Number,
        required: true
      },
      discount: {
        type: Number,
        default: 0, // Percentage discount (0-100)
        min: 0,
        max: 100
      },
      // How many of this line's quantity have been returned so far — caps
      // further returns and lets a line be partially returned over time.
      returnedQuantity: {
        type: Number,
        default: 0,
        min: 0
      }
    }
  ],
  customer: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Customer',
    default: null
  },
  totalAmount: {
    type: Number,
    required: true
  },
  cartDiscount: {
    type: Number,
    default: 0, // Percentage discount for entire cart (0-100)
    min: 0,
    max: 100
  },
  // Denormalized summary: payments[0].method when there's exactly one
  // payment line, else 'split'. Kept so every existing query/report/UI that
  // reads this flat field (shift cash reconciliation, dashboard breakdown,
  // the receipt) keeps working unchanged for the single-method case, which
  // is still the overwhelming majority of sales — payments[] below is the
  // actual source of truth.
  paymentMethod: {
    type: String,
    enum: ['cash', 'mpesa', 'card', 'store_credit', 'gift_card', 'split'],
    default: 'cash'
  },
  // One entry per payment method used on this sale. Almost always length 1;
  // length > 1 is a split-tender sale (any mix of cash/card/store_credit/
  // gift_card — M-Pesa can't be split in with others since its STK-push
  // confirmation is asynchronous, see finalizeSale). customer/giftCardCode
  // are only meaningful on a store_credit/gift_card line respectively.
  payments: {
    type: [
      {
        method: {
          type: String,
          enum: ['cash', 'mpesa', 'card', 'store_credit', 'gift_card'],
          required: true
        },
        amount: { type: Number, required: true },
        customer: { type: mongoose.Schema.Types.ObjectId, ref: 'Customer', default: null },
        giftCardCode: { type: String, default: null }
      }
    ],
    validate: {
      validator: (v) => Array.isArray(v) && v.length > 0,
      message: 'A sale must have at least one payment line'
    }
  },
  // Gift cards SOLD as a line item in this sale — separate from items[]
  // since a gift card isn't a Style/Variant and never touches stock.
  giftCardsSold: [
    {
      code: { type: String, required: true },
      amount: { type: Number, required: true }
    }
  ],
  // Set when paymentMethod === 'gift_card' — which card paid for this sale.
  giftCardRedeemed: {
    code: { type: String, default: null },
    amount: { type: Number, default: null }
  },
  status: {
    type: String,
    enum: ['completed', 'partially_returned', 'returned', 'voided'],
    default: 'completed'
  },
  refundedAmount: {
    type: Number,
    default: 0
  },
  // One entry per return transaction (a sale can be returned more than once,
  // potentially to different destinations) — refundedAmount is just
  // sum(returns[].amount), kept as a running total for cheap reads/aggregation.
  returns: [
    {
      destination: {
        type: String,
        enum: ['cash', 'original_payment', 'store_credit'],
        required: true
      },
      amount: { type: Number, required: true },
      items: [
        {
          variant: { type: mongoose.Schema.Types.ObjectId, ref: 'Variant' },
          quantity: Number
        }
      ],
      processedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
      },
      processedAt: { type: Date, default: Date.now }
    }
  ],
  cashier: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  // Idempotency key generated by the till before its first attempt to save
  // this sale. A retried request (lost response, offline queue replay) with
  // the same key returns the original sale instead of creating a second one.
  clientSaleId: { type: String, default: undefined },
  // Last SMS receipt sent for this sale (number masked — the full number
  // lives on the customer record, if they have one).
  receiptSms: {
    to: { type: String, default: null },
    at: { type: Date, default: null },
    status: { type: String, default: null }
  },
  // Admin who authorized an over-threshold discount at the till, if any.
  approvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  // Set when an admin voids the sale (a full reversal that keeps the record,
  // replacing the old hard delete).
  void: {
    by: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
    reason: { type: String, default: null },
    at: { type: Date, default: null }
  },
  // Optional so the API isn't a breaking change for callers that don't send
  // one — the POS UI's shift-open gate is what actually enforces the
  // discipline in practice.
  shift: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Shift',
    default: null
  },
  createdAt: {
    type: Date,
    default: Date.now
  },
  // KRA eTIMS submission state — set after finalizeSale commits, never
  // blocking the sale itself (see server/services/etims.js). etimsQrPayload
  // is deliberately separate from the existing receipt-lookup QR the client
  // generates from {id, total, date}; the two are never conflated.
  etimsStatus: {
    type: String,
    enum: ['not_submitted', 'pending', 'accepted', 'rejected', 'unreachable'],
    default: 'not_submitted'
  },
  etimsInvoiceNumber: { type: String, default: null },
  etimsQrPayload: { type: String, default: null },
  etimsSubmittedAt: { type: Date, default: null },
  // KRA invoice sequence number, assigned on first live submission and
  // reused on every retry so one sale can never become two invoices.
  etimsInvoiceSeq: { type: Number, default: null }
});

saleSchema.index({ clientSaleId: 1 }, { unique: true, sparse: true });

module.exports = mongoose.model('Sale', saleSchema);
